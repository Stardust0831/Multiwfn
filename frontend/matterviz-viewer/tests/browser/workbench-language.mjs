// End-to-end locale and naming acceptance against the real molecule/volume preview.
import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const preview = process.env.PREVIEW_URL || 'http://127.0.0.1:5197/'
const artifacts = process.env.ARTIFACT_DIR || '/tmp/multiwfn-workbench-language'
await mkdir(artifacts, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE, headless: true,
  args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, locale: 'en-US', acceptDownloads: true })
const errors = [], checks = []
page.on('pageerror', (error) => errors.push(String(error)))
const button = (name) => page.getByRole('button', { name, exact: true })
const record = (message) => { checks.push(message); console.log('PASS', message) }
const choose = async (label, value) => {
  await button(label).click()
  await page.getByRole('option', { name: value, exact: true }).click()
  await page.getByRole('listbox').waitFor({ state: 'hidden' })
}
const snapshot = async (chinese, name) => {
  await button(chinese ? '保存' : 'Save').click()
  const download = page.waitForEvent('download')
  await button(chinese ? '保存显示设置' : 'Save display settings').click()
  const file = path.join(artifacts, name + '.json')
  await (await download).saveAs(file)
  await page.getByRole('dialog', { name: chinese ? '保存选项' : 'Save controls', exact: true }).waitFor({ state: 'hidden' })
  return JSON.parse(await readFile(file, 'utf8'))
}
try {
  await page.goto(preview, { waitUntil: 'networkidle', timeout: 180000 })
  await page.waitForFunction(() => document.querySelector('.statusbar')?.textContent.includes('2 volume'))
  await page.locator('canvas').waitFor()
  assert.equal(await page.locator('html').getAttribute('lang'), 'en')
  assert.match(await button('Atom material preset').innerText(), /Renderer default/)
  await choose('Scene appearance preset', 'Studio lighting')
  await choose('Atom material preset', 'Balanced')
  const canvasBounds = await page.locator('canvas').boundingBox()
  await page.mouse.move(canvasBounds.x + canvasBounds.width * .55, canvasBounds.y + canvasBounds.height * .5)
  await page.mouse.down()
  await page.mouse.move(canvasBounds.x + canvasBounds.width * .65, canvasBounds.y + canvasBounds.height * .55, { steps: 12 })
  await page.mouse.up()
  await page.waitForTimeout(500)
  const before = await snapshot(false, 'locale-before')
  assert.equal(before.structureAppearance.lightingRig, 'tmim')
  assert.equal(before.structureAppearance.atomStyle, 'current')
  await page.evaluate(() => { window.localeTestCanvas = document.querySelector('canvas') })
  await button('切换到中文').click()
  await button('视图').waitFor()
  assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN')
  assert.match(await button('光照预设').innerText(), /影棚布光/)
  assert.match(await button('原子材质预设').innerText(), /均衡/)
  assert.match(await page.locator('.statusbar').innerText(), /2 组体数据/)
  assert.equal(Number(await page.getByRole('slider', { name: '补光强度', exact: true }).getAttribute('aria-valuenow')), .85)
  assert.doesNotMatch(await page.locator('body').innerText(), /TMIM/)
  const after = await snapshot(true, 'locale-after')
  assert.deepEqual(after, before, 'language switch must preserve every saved scientific and display setting')
  assert.equal(await page.evaluate(() => document.querySelector('canvas') === window.localeTestCanvas), true)
  assert.equal(await page.locator('canvas').count(), 1)
  await page.screenshot({ path: path.join(artifacts, 'language-zh.png') })
  record('中文切换保留同一画布、视角、光照、材质及体数据；旧预设 ID 兼容')

  await button('光照预设').click()
  await page.getByRole('option', { name: '标准布光', exact: true }).waitFor()
  await page.getByRole('option', { name: '影棚布光', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await button('工具').click()
  assert.equal(await button('静电势表面').isDisabled(), true)
  await button('此会话不支持静电势计算').hover()
  await page.getByRole('tooltip', { name: '此会话不支持静电势计算', exact: true }).waitFor()
  await page.screenshot({ path: path.join(artifacts, 'language-tools-zh.png') })
  await page.keyboard.press('Escape'); await page.keyboard.press('Escape')
  await page.getByRole('tab', { name: '表面', exact: true }).click()
  await button('柔和高光').waitFor()
  await choose('经典表面材质预设', '拉丝金属')
  await page.locator('.inspector-tab-bar').getByRole('button', { name: '打开体数据图层（2）', exact: true }).click()
  await page.locator('.layer-panel').getByText('着色依据', { exact: true }).first().waitFor()
  assert.match(await page.locator('.layer-panel').innerText(), /Density/)
  await page.locator('.layer-panel').getByRole('button', { name: '关闭', exact: true }).click()
  await button('视图').click(); await button('二维切片').click()
  await page.getByRole('complementary', { name: '二维体数据切片', exact: true }).waitFor()
  await button('关闭切片面板').click()
  record('中文下拉选项、表面材质、图层、切片及禁用原因可用；数据名称保持原文')

  await button('Switch to English').click()
  await button('View').waitFor()
  await button('Open surfaces inspector').click()
  assert.match(await button('Original surface material preset').innerText(), /BrushedMetal/)
  await page.screenshot({ path: path.join(artifacts, 'language-en.png') })
  await button('切换到中文').click()
  await page.reload({ waitUntil: 'networkidle' })
  await button('视图').waitFor()
  assert.equal(await page.evaluate(() => localStorage.getItem('multiwfn-ui-language')), 'zh')
  assert.match(await page.locator('.statusbar').innerText(), /已载入 2 个体数据图层/)
  await page.setViewportSize({ width: 600, height: 820 })
  await button('Switch to English').waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await page.screenshot({ path: path.join(artifacts, 'language-narrow-zh.png') })
  await button('Switch to English').click()
  await page.reload({ waitUntil: 'networkidle' })
  await button('View').waitFor()
  record('双向切换、刷新后语言记忆及窄屏布局通过')

  const chinese = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1200, height: 800 } })
  const firstVisit = await chinese.newPage()
  firstVisit.on('pageerror', (error) => errors.push(String(error)))
  await firstVisit.goto(preview, { waitUntil: 'networkidle', timeout: 120000 })
  await firstVisit.getByRole('button', { name: '视图', exact: true }).waitFor()
  assert.equal(await firstVisit.locator('html').getAttribute('lang'), 'zh-CN')
  await chinese.close()
  record('首次打开跟随浏览器中文语言')
  assert.deepEqual(errors, [])
  await writeFile(path.join(artifacts, 'language-verification.json'), JSON.stringify({ preview, checks, errors }, null, 2))
} catch (error) {
  await page.screenshot({ path: path.join(artifacts, 'language-failure.png') }).catch(() => {})
  console.error({ checks, errors }); throw error
} finally { await browser.close() }
